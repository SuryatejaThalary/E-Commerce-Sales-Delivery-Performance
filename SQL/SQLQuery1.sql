WITH SellerPerformance AS
(
    SELECT
        s.seller_id,
        s.seller_name,
        SUM(o.net_sales) AS total_sales,
        SUM(o.profit) AS total_profit,
        SUM(o.profit) * 100.0 /
            NULLIF(SUM(o.net_sales), 0) AS profit_margin
    FROM Orders o
    JOIN Sellers s
        ON s.seller_id = o.seller_id
    GROUP BY
        s.seller_id,
        s.seller_name
)
SELECT
    seller_id,
    seller_name,
    total_sales,
    total_profit,
    profit_margin
FROM SellerPerformance
WHERE total_sales > (SELECT AVG(total_sales) FROM SellerPerformance)
  AND profit_margin < (SELECT AVG(profit_margin) FROM SellerPerformance)
ORDER BY total_sales DESC;


