--For example:

--View 1 — Sales Analysis
--vw_SalesAnalysis

--Containing:

--Order ID
--Order Date
--Customer
--Product
--Category
--Brand
--Seller
--Region
--Quantity
--Gross Sales
--Discount
--Net Sales
--Profit
--Profit Margin
--Sales Channel
select * from  products 
select * from orders 
select * from sellers 

create or alter view vw_SalesAnalysis
as 
select o.order_id,o.order_date,c.customer_name,p.product_name,p.category,
		p.brand,s.seller_name,c.region ,o.quantity ,o.gross_sales ,
		sum(o.discount_amount) as discount,o.net_sales  ,o.profit  ,
		((sum(o.profit) *100)/sum(o.net_sales)) as profitmrgn,o.sales_channel 
		from orders o 
		join products p on  p.product_id=o.product_id
		join Sellers s on s.seller_id=o.seller_id
		join customers c on c.customer_id=o.customer_id
		group by o.order_id,o.order_date,c.customer_name,p.product_name,p.category,
		p.brand,s.seller_name,c.region,o.sales_channel,o.quantity,o.gross_sales,o.net_sales,o.profit

select * from vw_SalesAnalysis


--View 2 — Customer Analysis
--vw_CustomerAnalysis

--Containing:

--Customer
--Region
--Customer Segment
--Total Orders
--Total Sales
--Total Profit
--Average Order Value

create or alter view vw_CustomerAnalysis
as
select c.customer_name,c.region,c.customer_segment,count(distinct o.order_id) as orders ,
		sum(o.net_sales) as sales,sum(o.profit)as profit ,
		sum(o.net_sales)/count(distinct o.order_id) as avgval
		from orders o 
		join customers c on c.customer_id=o.customer_id
		group by c.customer_id,c.customer_name,c.region,c.customer_segment


select *from vw_CustomerAnalysis


--View 3 — Product Analysis
--vw_ProductAnalysis

--Containing:

--Product
--Category
--Brand
--Orders
--Quantity Sold
--Sales
--Profit
--Profit Margin
--Rating

create view vw_ProductAnalysis
as 
select p.product_name,p.category,p.brand,count(distinct o.order_id) as orders,sum(o.quantity) as soldqty,
				sum(o.net_sales) as sales,sum(o.profit) as profit,
				((sum(o.profit)*100)/sum(o.net_sales)) as mrgn,p.product_rating from products p 
				join orders o on o.product_id=p.product_id
				group by p.product_name,p.category,p.brand,p.product_rating


select * from vw_ProductAnalysis


--View 4 — Seller Performance
--vw_SellerPerformance

--Containing:

--Seller
--Orders
--Sales
--Profit
--Profit Margin
--Seller Rating

select * from sellers



create view vw_SellerPerformance
as 
select s.seller_name,count(distinct o.order_id) as orders ,
		sum(o.net_sales) as sales,sum(o.profit) as profit,
		((sum(o.profit)*100)/sum(o.net_sales)) as mrgn,
		s.seller_rating from sellers s 
		join orders o on o.seller_id=s.seller_id
		group by s.seller_name,s.seller_rating


select * from vw_SellerPerformance


--View 5 — Delivery Performance
--vw_DeliveryPerformance

--Containing:

--Order ID
--Region
--Delivery Partner
--Promised Days
--Actual Days
--Delay Days
--Delivery Status
--Delivery Cost
--Distance

select * from orders 
select * from Deliveries
select * from customers 

create view vw_DeliveryPerformance
as 
select o.order_id,c.region ,d.delivery_partner,d.promised_days,d.actual_delivery_days,
			(convert(int,d.actual_delivery_days))-(convert(bigint,d.promised_days)) as delaydays,
				d.delivery_status,d.delivery_cost,d.distance_km from orders o 
				join Deliveries d on d.order_id=o.order_id
				join customers c on c.customer_id=o.customer_id


select * from vw_DeliveryPerformance



--View 6 — Payment Analysis
--VW_PAYMENTANALYSIS

--Containing:

--Payment Method
--Payment Status
--Transactions
--Amount Paid
--Transaction Fees

CREATE VIEW VW_PAYMENTANALYSIS
AS
SELECT
    p.payment_method,
    p.payment_status,
    COUNT(DISTINCT p.order_id) AS transactions,
    SUM(p.amount_paid) AS amount_paid,
    SUM(p.transaction_fee) AS transaction_fees
FROM payments p
JOIN orders o
    ON o.order_id = p.order_id
GROUP BY
    p.payment_method,
    p.payment_status;


select * from VW_PAYMENTANALYSIS


